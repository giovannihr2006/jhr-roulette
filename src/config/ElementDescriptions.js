/**
 * Función auxiliar para obtener descripción de un elemento
 * @param {number} elementId - ID del elemento (1-27)
 * @returns {Object} Descripción del elemento o null si no existe
 */
export const getElementDescription = (elementId) => {
  if (!ELEMENT_DESCRIPTIONS[elementId]) {
    console.warn(`⚠️ Elemento ${elementId} no encontrado en ElementDescriptions`)
    return null
  }
  return ELEMENT_DESCRIPTIONS[elementId]
}

/**
 * Función auxiliar para listar todos los IDs de elementos
 * @returns {number[]} Array de IDs de elementos
 */
export const getAllElementIds = () => {
  return Object.keys(ELEMENT_DESCRIPTIONS).map(Number).sort((a, b) => a - b)
}
